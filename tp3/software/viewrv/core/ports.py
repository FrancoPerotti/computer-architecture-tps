"""Ports for external collaborators; device libraries belong to adapters."""

from typing import Protocol


class Assembler(Protocol):
    def assemble(self, source_text: str): ...


class Storage(Protocol):
    def read_source(self, path: str): ...
    def write_source(self, path: str, text: str, allow_create: bool): ...
    def read_recoveries(self): ...
    def write_recovery(self, snapshot: dict): ...
    def delete_recovery(self, program_id: str): ...
    def read_preferences(self): ...
    def write_preferences(self, preferences: dict): ...
    def append_record(self, unit: dict): ...
    def read_record(self, session_id: str, summary: bool = False): ...
    def list_records(self): ...


class SerialPort(Protocol):
    timeout: float
    write_timeout: float

    @property
    def in_waiting(self) -> int: ...
    def read(self, size: int) -> bytes: ...
    def write(self, data: bytes) -> int: ...
    def reset_output_buffer(self): ...
    def close(self): ...
